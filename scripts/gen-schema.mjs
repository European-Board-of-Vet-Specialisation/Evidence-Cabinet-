// Bundle migrations/*.sql into src/schema.gen.ts, so the cabinet can set up its own database on
// first use (src/migrate.ts) whatever deploy command a College's build runs.
//   node scripts/gen-schema.mjs           write it
//   node scripts/gen-schema.mjs --check   fail if it is out of date (npm test runs this)
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
const files = readdirSync('migrations').filter(f => f.endsWith('.sql')).sort()
const out = `// GENERATED by scripts/gen-schema.mjs from migrations/*.sql — do not edit.\nexport const MIGRATIONS: Array<{ name: string; sql: string }> = ${JSON.stringify(files.map(name => ({ name, sql: readFileSync(`migrations/${name}`, 'utf8') })), null, 2)}\n`
const target = 'src/schema.gen.ts'
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) { console.error(`${target} is out of date: run node scripts/gen-schema.mjs`); process.exit(1) }
} else writeFileSync(target, out)
